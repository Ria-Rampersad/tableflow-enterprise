-- 01_account_setup.sql — run once as ACCOUNTADMIN / SYSADMIN in Snowflake.
-- Creates the warehouse, database, schemas (RAW -> STAGING -> ANALYTICS), a least-privilege
-- loader role and a key-pair-authenticated service user. NOT executed by this project:
-- no Snowflake account is connected (see documentation/05_DATABASE_AND_SQL_HANDBOOK.md).

USE ROLE SYSADMIN;
CREATE WAREHOUSE IF NOT EXISTS TABLEFLOW_WH
  WAREHOUSE_SIZE = 'XSMALL' AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE
  COMMENT = 'TableFlow ELT + BI (auto-suspends after 60s to control credits)';

CREATE DATABASE IF NOT EXISTS TABLEFLOW_ANALYTICS;
CREATE SCHEMA IF NOT EXISTS TABLEFLOW_ANALYTICS.RAW       COMMENT = 'Exact copies of operational extracts';
CREATE SCHEMA IF NOT EXISTS TABLEFLOW_ANALYTICS.STAGING   COMMENT = 'Typed, cleaned, de-duplicated';
CREATE SCHEMA IF NOT EXISTS TABLEFLOW_ANALYTICS.ANALYTICS COMMENT = 'Dimensional model + reporting marts';

USE ROLE SECURITYADMIN;
CREATE ROLE IF NOT EXISTS TABLEFLOW_LOADER;
CREATE ROLE IF NOT EXISTS TABLEFLOW_REPORTER;
GRANT USAGE ON WAREHOUSE TABLEFLOW_WH TO ROLE TABLEFLOW_LOADER;
GRANT USAGE ON WAREHOUSE TABLEFLOW_WH TO ROLE TABLEFLOW_REPORTER;
GRANT USAGE ON DATABASE TABLEFLOW_ANALYTICS TO ROLE TABLEFLOW_LOADER;
GRANT USAGE ON DATABASE TABLEFLOW_ANALYTICS TO ROLE TABLEFLOW_REPORTER;
GRANT ALL ON SCHEMA TABLEFLOW_ANALYTICS.RAW TO ROLE TABLEFLOW_LOADER;
GRANT ALL ON SCHEMA TABLEFLOW_ANALYTICS.STAGING TO ROLE TABLEFLOW_LOADER;
GRANT ALL ON SCHEMA TABLEFLOW_ANALYTICS.ANALYTICS TO ROLE TABLEFLOW_LOADER;
GRANT USAGE ON SCHEMA TABLEFLOW_ANALYTICS.ANALYTICS TO ROLE TABLEFLOW_REPORTER;
GRANT SELECT ON FUTURE TABLES IN SCHEMA TABLEFLOW_ANALYTICS.ANALYTICS TO ROLE TABLEFLOW_REPORTER;

-- Service user: key-pair auth only (no password). Generate the key with:
--   python -m app.security.keypair ./keys      (from /backend)
-- then paste the public key body (without BEGIN/END lines) below.
CREATE USER IF NOT EXISTS TABLEFLOW_SVC
  TYPE = SERVICE
  DEFAULT_ROLE = TABLEFLOW_LOADER
  DEFAULT_WAREHOUSE = TABLEFLOW_WH
  RSA_PUBLIC_KEY = '<paste public key body here>'
  COMMENT = 'TableFlow ELT loader (key-pair auth)';
GRANT ROLE TABLEFLOW_LOADER TO USER TABLEFLOW_SVC;
-- Verify the fingerprint matches app.security.keypair.public_key_fingerprint():
--   DESC USER TABLEFLOW_SVC;  -> RSA_PUBLIC_KEY_FP

USE ROLE TABLEFLOW_LOADER;
USE SCHEMA TABLEFLOW_ANALYTICS.RAW;
CREATE FILE FORMAT IF NOT EXISTS CSV_TF TYPE = CSV SKIP_HEADER = 1 FIELD_OPTIONALLY_ENCLOSED_BY = '"'
  NULL_IF = ('', 'NULL') EMPTY_FIELD_AS_NULL = TRUE;
CREATE STAGE IF NOT EXISTS TF_STAGE FILE_FORMAT = CSV_TF COMMENT = 'Internal stage for PUT + COPY INTO';
